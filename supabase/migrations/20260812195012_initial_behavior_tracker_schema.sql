  ('green', 1.0, 2),
  ('yellow', -0.5, 3),
  ('orange', -1.0, 4),
  ('red', -2.0, 5);

create table public.behavior_entries (
  id bigint generated by default as identity primary key,
  child_id bigint not null references public.children(id) on delete restrict,
  entry_date date not null default current_date,
  entry_type text not null check (entry_type in ('behavior','status')),
  card text check (card in ('diamond','green','yellow','orange','red')),
  day_status text check (day_status in ('absent','sick','didnt_report','field_trip','closed','other')),
  points numeric(4,1) not null default 0,
  note text,
  recorded_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint behavior_entry_shape check (
    (entry_type = 'behavior' and card is not null and day_status is null)
    or
    (entry_type = 'status' and card is null and day_status is not null)
  ),
  constraint one_daily_entry_per_child unique (child_id, entry_date)
);

create table public.app_settings (
  id smallint primary key default 1 check (id = 1),
  wheel_rule_mode text not null default 'pending' check (wheel_rule_mode in ('pending','points_per_spin','tiers')),
  points_per_spin numeric(6,2),
  wheel_rule_notes text,
  updated_at timestamptz not null default now()
);

