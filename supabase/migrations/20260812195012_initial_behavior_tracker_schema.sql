create or replace function public.set_behavior_entry_points()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.entry_type = 'behavior' then
    select points into new.points from public.card_rules where card = new.card;
    if new.points is null then
      raise exception 'Unknown behavior card: %', new.card;
    end if;
  else
    new.points := 0;
  end if;
  new.updated_at := now();
  return new;
end;
$$;

create trigger behavior_entries_set_points
before insert or update of entry_type, card, day_status
on public.behavior_entries
for each row execute function public.set_behavior_entry_points();

