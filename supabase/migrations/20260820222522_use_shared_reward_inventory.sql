  insert into public.free_prize_wins(child_id,month_start,category_id,tier_id,prize_id,prize_name_snapshot,category_name_snapshot,tier_name_snapshot,reason,recorded_by)
  values(p_child_id,m,cid,tid,pid,pname,cname,tname,nullif(trim(coalesce(p_reason,'')),''),auth.uid()) returning id,public.free_prize_wins.won_at into wid,won_time;
  return query select wid,pid,pname,cname,tname,left_qty,won_time;
end;
$$;

