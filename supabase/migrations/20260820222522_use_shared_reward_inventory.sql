  select t.id,t.name,t.min_spins into tid,tname,tmin from public.wheel_tiers t where t.slug=p_tier_slug and t.active;
  if cid is null or tid is null then raise exception 'Wheel unavailable'; end if;
  select sum(s.weight) into total_weight from public.wheel_stock s join public.wheel_prizes p on p.id=s.prize_id join public.wheel_tiers rt on rt.id=p.required_tier_id where p.active and p.category_id=cid and rt.active and rt.min_spins<=tmin and s.enabled and s.quantity_remaining>0 and s.weight>0;
  if coalesce(total_weight,0)<=0 then raise exception 'No in-stock prizes are available on this wheel'; end if;
  target_weight:=random()*total_weight;
  with q as (
    select s.id as stock_key,p.id as prize_key,p.name as prize_label,sum(s.weight) over(order by p.id) as running_weight
    from public.wheel_stock s join public.wheel_prizes p on p.id=s.prize_id join public.wheel_tiers rt on rt.id=p.required_tier_id
    where p.active and p.category_id=cid and rt.active and rt.min_spins<=tmin and s.enabled and s.quantity_remaining>0 and s.weight>0
  ) select q.stock_key,q.prize_key,q.prize_label into sid,pid,pname from q where q.running_weight>target_weight order by q.running_weight limit 1;
  update public.wheel_stock s set quantity_remaining=s.quantity_remaining-1,updated_at=now() where s.id=sid and s.quantity_remaining>0 returning s.quantity_remaining into left_qty;
