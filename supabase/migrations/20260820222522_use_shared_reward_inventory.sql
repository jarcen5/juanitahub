create or replace function public.get_available_free_wheel(p_month_start date, p_category_slug text, p_tier_slug text)
returns table(inventory_id bigint, prize_id bigint, prize_name text, required_tier_name text, weight numeric, quantity_remaining integer)
language plpgsql stable security definer set search_path=public
as $$
declare cid bigint; selected_tier_min integer;
begin
  if not public.current_user_is_active_staff() then raise exception 'Not authorized'; end if;
  select c.id into cid from public.wheel_categories c where c.slug=p_category_slug and c.active;
  select t.min_spins into selected_tier_min from public.wheel_tiers t where t.slug=p_tier_slug and t.active;
  if cid is null or selected_tier_min is null then raise exception 'Wheel unavailable'; end if;
  return query
  select s.id,p.id,p.name,rt.name,s.weight,s.quantity_remaining
  from public.wheel_stock s
  join public.wheel_prizes p on p.id=s.prize_id
  join public.wheel_tiers rt on rt.id=p.required_tier_id
  where p.active and p.category_id=cid and rt.active and rt.min_spins<=selected_tier_min and s.enabled and s.quantity_remaining>0 and s.weight>0
  order by p.id;
end;
$$;

create or replace function public.spin_free_reward_wheel(p_child_id bigint,p_month_start date,p_category_slug text,p_tier_slug text,p_reason text default null)
