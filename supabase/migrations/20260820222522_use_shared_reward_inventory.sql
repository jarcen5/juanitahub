create table if not exists public.wheel_stock (
  id bigint generated by default as identity primary key,
  prize_id bigint not null unique references public.wheel_prizes(id) on delete cascade,
  quantity_start integer not null check (quantity_start >= 0),
  quantity_remaining integer not null check (quantity_remaining >= 0 and quantity_remaining <= quantity_start),
  weight numeric not null check (weight > 0),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

insert into public.wheel_stock(prize_id, quantity_start, quantity_remaining, weight, enabled)
select distinct on (i.prize_id)
  i.prize_id, i.quantity_start, i.quantity_remaining, i.weight, i.enabled
from public.wheel_inventory i
order by i.prize_id, i.month_start desc
on conflict (prize_id) do nothing;

alter table public.wheel_stock enable row level security;

drop policy if exists wheel_stock_active_staff_read on public.wheel_stock;
create policy wheel_stock_active_staff_read on public.wheel_stock
for select to authenticated
using (public.current_user_is_active_staff());

drop policy if exists wheel_stock_admin_manage on public.wheel_stock;
create policy wheel_stock_admin_manage on public.wheel_stock
for all to authenticated
using (public.current_user_is_admin())
with check (public.current_user_is_admin());

grant select, insert, update, delete on public.wheel_stock to authenticated;
revoke all on public.wheel_stock from anon;
grant usage, select on sequence public.wheel_stock_id_seq to authenticated;
revoke all on sequence public.wheel_stock_id_seq from anon;

