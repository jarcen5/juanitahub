grant select,insert,update,delete on public.learning_goal_bonus_points to service_role;
grant select,insert,update,delete on public.learning_student_achievements to service_role;

create or replace function public.validate_learning_goal_open_limit()
returns trigger
language plpgsql
security invoker
set search_path=public
as $$
declare
  v_open integer;
begin
  new.title := nullif(trim(coalesce(new.title,'')),'');
  if new.title is null then raise exception 'Goal title is required'; end if;
  new.updated_at := now();

  if new.status in ('active','reached') then
    select count(*) into v_open
    from public.learning_goals g
    where g.child_id=new.child_id
      and g.status in ('active','reached')
      and (tg_op='INSERT' or g.id<>new.id);
    if v_open >= 2 then
      raise exception 'A student can have at most two open point-earning goals at a time.';
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists learning_goals_open_limit on public.learning_goals;
create trigger learning_goals_open_limit
before insert or update on public.learning_goals
for each row execute function public.validate_learning_goal_open_limit();
;