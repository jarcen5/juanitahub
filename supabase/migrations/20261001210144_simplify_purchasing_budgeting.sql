create or replace function public.set_purchase_item_simple_timestamps()
returns trigger
language plpgsql
set search_path = 'public', 'pg_temp'
as $$
begin
  if new.item_status = 'need' then
    new.purchased_at := null;
    new.received_at := null;
  elsif new.item_status = 'purchased' then
    new.purchased_at := coalesce(new.purchased_at, now());
    new.received_at := null;
  elsif new.item_status = 'received' then
    new.purchased_at := coalesce(new.purchased_at, now());
    new.received_at := coalesce(new.received_at, now());
  end if;
  return new;
end;
$$;

