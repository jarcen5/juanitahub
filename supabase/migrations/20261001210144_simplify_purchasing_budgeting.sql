create or replace function public.sync_purchase_item_budget()
returns trigger
language plpgsql
set search_path = 'public', 'pg_temp'
as $$
declare
  v_budget_id bigint;
  v_budget_item_id bigint;
begin
  select budget_id into v_budget_id
  from public.purchase_requests
  where id = new.purchase_request_id;

  if v_budget_id is null then
    delete from public.budget_spend_entries where purchase_item_id = new.id;
    delete from public.budget_items where purchase_item_id = new.id;
    return new;
  end if;

  insert into public.budget_items(
    budget_id, purchase_item_id, description, category, planned_amount,
    counts_toward_plan, notes, active, created_by, updated_by
  )
  values (
    v_budget_id, new.id, new.description, coalesce(nullif(btrim(new.category_tag), ''), 'Other'),
    new.quantity * new.estimated_unit_cost, true, new.notes, true, auth.uid(), auth.uid()
  )
  on conflict (purchase_item_id) where purchase_item_id is not null
  do update set
    budget_id = excluded.budget_id,
    description = excluded.description,
    category = excluded.category,
    planned_amount = excluded.planned_amount,
    notes = excluded.notes,
    active = true,
    updated_by = auth.uid()
  returning id into v_budget_item_id;

  if new.item_status in ('purchased','received') then
    insert into public.budget_spend_entries(
      budget_id, budget_item_id, purchase_item_id, description, category,
      amount, spent_on, notes, created_by, updated_by
    )
    values (
      v_budget_id, v_budget_item_id, new.id, new.description,
      coalesce(nullif(btrim(new.category_tag), ''), 'Other'),
      new.quantity * coalesce(new.actual_unit_cost, new.estimated_unit_cost),
      coalesce(new.purchased_at::date, current_date),
      new.notes, auth.uid(), auth.uid()
    )
    on conflict (purchase_item_id) where purchase_item_id is not null
    do update set
      budget_id = excluded.budget_id,
      budget_item_id = excluded.budget_item_id,
      description = excluded.description,
      category = excluded.category,
      amount = excluded.amount,
      spent_on = excluded.spent_on,
      notes = excluded.notes,
      updated_by = auth.uid();
  else
    delete from public.budget_spend_entries where purchase_item_id = new.id;
  end if;

  return new;
end;
$$;

