create or replace view public.budget_simple_summary
with (security_invoker = true)
as
select
  b.id as budget_id,
  b.allocated_amount,
  coalesce((
    select sum(i.planned_amount)
    from public.budget_items i
    where i.budget_id = b.id and i.active and i.counts_toward_plan
  ), 0)::numeric as planned_amount,
  coalesce((
    select sum(s.amount)
    from public.budget_spend_entries s
    where s.budget_id = b.id
  ), 0)::numeric as spent_amount,
  (b.allocated_amount - coalesce((
    select sum(s.amount)
    from public.budget_spend_entries s
    where s.budget_id = b.id
  ), 0))::numeric as remaining_amount
from public.budget_accounts b;

