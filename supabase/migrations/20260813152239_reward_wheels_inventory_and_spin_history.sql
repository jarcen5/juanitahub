create table if not exists public.wheel_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  display_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wheel_tiers (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  min_spins integer not null check (min_spins >= 1),
  display_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.wheel_prizes (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.wheel_categories(id) on delete restrict,
  name text not null,
  required_tier_id bigint not null references public.wheel_tiers(id) on delete restrict,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (category_id, name)
);

create table if not exists public.wheel_inventory (
  id bigint generated by default as identity primary key,
  prize_id bigint not null references public.wheel_prizes(id) on delete cascade,
  month_start date not null check (month_start = date_trunc('month', month_start)::date),
  quantity_start integer not null default 0 check (quantity_start >= 0),
  quantity_remaining integer not null default 0 check (quantity_remaining >= 0),
  weight numeric(10,2) not null default 1 check (weight > 0),
  enabled boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (prize_id, month_start),
  check (quantity_remaining <= quantity_start)
);

create table if not exists public.prize_wins (
  id bigint generated by default as identity primary key,
  child_id bigint not null references public.children(id) on delete restrict,
  month_start date not null check (month_start = date_trunc('month', month_start)::date),
  category_id bigint not null references public.wheel_categories(id) on delete restrict,
  tier_id bigint not null references public.wheel_tiers(id) on delete restrict,
  prize_id bigint not null references public.wheel_prizes(id) on delete restrict,
  spin_number integer not null check (spin_number >= 1),
  earned_spins_snapshot integer not null check (earned_spins_snapshot >= 1),
  prize_name_snapshot text not null,
  category_name_snapshot text not null,
  tier_name_snapshot text not null,
  recorded_by uuid not null references auth.users(id) on delete restrict,
  won_at timestamptz not null default now(),
  unique (child_id, month_start, spin_number)
);

