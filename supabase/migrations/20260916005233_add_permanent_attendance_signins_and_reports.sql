create table public.attendance_visits (
  id bigint generated by default as identity primary key,
  service_date date not null default current_date,
  participant_type text not null check (participant_type in ('child', 'adult', 'family', 'visitor')),
  child_id bigint references public.children(id) on delete restrict,
  visitor_name text,
  purpose text,
  signed_in_at timestamptz not null default now(),
  signed_out_at timestamptz,
  source text not null default 'staff' check (source in ('kiosk', 'staff', 'manual', 'import')),
  status text not null default 'active' check (status in ('active', 'voided')),
  recorded_by uuid not null references auth.users(id) on delete restrict,
  voided_at timestamptz,
  voided_by uuid references auth.users(id) on delete restrict,
  void_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint attendance_visits_participant_shape check (
    (participant_type = 'child' and child_id is not null and visitor_name is null)
    or
    (participant_type in ('adult', 'family', 'visitor') and child_id is null and nullif(btrim(visitor_name), '') is not null)
  ),
  constraint attendance_visits_signout_order check (signed_out_at is null or signed_out_at >= signed_in_at),
  constraint attendance_visits_void_fields check (
    (status = 'active' and voided_at is null and voided_by is null)
    or
    (status = 'voided' and voided_at is not null and voided_by is not null and nullif(btrim(void_reason), '') is not null)
  )
);

create unique index attendance_visits_one_active_child_per_day
  on public.attendance_visits (child_id, service_date)
  where participant_type = 'child' and status = 'active';

create index attendance_visits_service_date_status_idx
  on public.attendance_visits (service_date, status);

create index attendance_visits_child_date_idx
  on public.attendance_visits (child_id, service_date)
  where child_id is not null;

create table public.attendance_wellbeing (
  visit_id bigint primary key references public.attendance_visits(id) on delete restrict,
  mood text not null check (mood in ('good', 'okay', 'hard_day')),
  recorded_by uuid not null references auth.users(id) on delete restrict,
  recorded_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
