create table if not exists public.learning_assignment_schedules (
  id bigint generated by default as identity primary key,
  child_id bigint not null references public.children(id) on delete cascade,
  assignment_id bigint not null references public.learning_assignments(id) on delete restrict,
  repeat_mode text not null check (repeat_mode = any (array['daily'::text,'weekdays'::text,'weekly'::text,'custom'::text])),
  days_of_week smallint[] not null,
  start_date date not null,
  end_date date not null,
  active boolean not null default true,
  created_by uuid not null references auth.users(id),
  created_at timestamptz not null default now(),
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now(),
  constraint learning_assignment_schedules_dates_check check (end_date >= start_date),
  constraint learning_assignment_schedules_days_check check (
    cardinality(days_of_week) between 1 and 7
    and days_of_week <@ array[0,1,2,3,4,5,6]::smallint[]
  )
);

